"""Generate reference vectors for the FreeRTOS target crypto/NWK tests.

The vectors come from an independent implementation (pyca/cryptography,
OpenSSL AES and AES-CCM). Output is deterministic and committed:
firmware/freertos/tests/vectors_crypto.h. Re-run after changing the cases:

  python tools/gen_freertos_vectors.py
"""
from pathlib import Path
import hashlib

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.primitives.ciphers.aead import AESCCM

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware/freertos/tests/vectors_crypto.h"


def det(label, n):
    """Deterministic pseudo-random bytes (not secret, test data only)."""
    out = b""
    i = 0
    while len(out) < n:
        out += hashlib.sha256(f"{label}:{i}".encode()).digest()
        i += 1
    return out[:n]


def aes(key, block):
    e = Cipher(algorithms.AES(key), modes.ECB()).encryptor()
    return e.update(block) + e.finalize()


def mmo(msg):
    bits = len(msg) * 8
    m = msg + b"\x80"
    while len(m) % 16 != 14:
        m += b"\x00"
    m += bits.to_bytes(2, "big")
    h = bytes(16)
    for i in range(0, len(m), 16):
        blk = m[i:i + 16]
        h = bytes(a ^ b for a, b in zip(aes(h, blk), blk))
    return h


def hmac_mmo(key, msg):
    ipad = bytes(k ^ 0x36 for k in key)
    opad = bytes(k ^ 0x5C for k in key)
    return mmo(opad + mmo(ipad + msg))


def c_bytes(b):
    return "{" + ", ".join(f"0x{x:02x}" for x in b) + "}" if b else "{0}"


def main():
    lines = ["/* Generated by tools/gen_freertos_vectors.py from pyca/cryptography. */",
             "#ifndef VECTORS_CRYPTO_H", "#define VECTORS_CRYPTO_H", "#include <stdint.h>", "#include <stddef.h>"]
    # AES-128: FIPS-197 C.1 + derived blocks.
    lines.append("typedef struct { uint8_t key[16], in[16], out[16]; } aes_vec_t;")
    aes_cases = [(bytes(range(16)), bytes.fromhex("00112233445566778899aabbccddeeff"))]
    aes_cases += [(det(f"aes-k{i}", 16), det(f"aes-p{i}", 16)) for i in range(8)]
    lines.append("static const aes_vec_t AES_VECTORS[] = {")
    for k, p in aes_cases:
        lines.append(f"  {{{c_bytes(k)}, {c_bytes(p)}, {c_bytes(aes(k, p))}}},")
    lines.append("};")
    # CCM* with L=2 (13-byte nonce), M in {4, 8, 16}.
    lines.append("typedef struct { uint8_t key[16], nonce[13]; uint8_t aad[40]; size_t aad_len;"
                 " uint8_t pt[80]; size_t pt_len; uint8_t ct[80]; uint8_t mic[16]; size_t m; } ccm_vec_t;")
    lines.append("static const ccm_vec_t CCM_VECTORS[] = {")
    # RFC 3610 packet vector #1 (M=8).
    rfc_key = bytes(range(0xC0, 0xD0))
    rfc_nonce = bytes.fromhex("00000003020100A0A1A2A3A4A5")
    cases = [(rfc_key, rfc_nonce, bytes(range(8)), bytes(range(8, 31)), 8)]
    for i, (alen, plen, m) in enumerate([(0, 1, 4), (14, 0, 4), (1, 15, 4), (15, 16, 4), (16, 17, 8),
                                          (23, 33, 4), (37, 64, 16), (40, 80, 4), (2, 79, 8)]):
        cases.append((det(f"ccm-k{i}", 16), det(f"ccm-n{i}", 13), det(f"ccm-a{i}", alen),
                      det(f"ccm-p{i}", plen), m))
    for key, nonce, aad, pt, m in cases:
        sealed = AESCCM(key, tag_length=m).encrypt(nonce, pt, aad if aad else None)
        ct, mic = sealed[:-m], sealed[-m:]
        lines.append(f"  {{{c_bytes(key)}, {c_bytes(nonce)}, {c_bytes(aad)}, {len(aad)}, {c_bytes(pt)}, "
                     f"{len(pt)}, {c_bytes(ct)}, {c_bytes(mic)}, {m}}},")
    lines.append("};")
    assert cases[0] and AESCCM(rfc_key, tag_length=8).encrypt(rfc_nonce, bytes(range(8, 31)), bytes(range(8))).hex() \
        == "588c979a61c663d2f066d0c2c0f989806d5f6b61dac38417e8d12cfdf926e0"
    # MMO hash and HMAC-MMO.
    lines.append("typedef struct { uint8_t msg[48]; size_t len; uint8_t digest[16]; } mmo_vec_t;")
    lines.append("static const mmo_vec_t MMO_VECTORS[] = {")
    for n in [0, 1, 13, 14, 15, 16, 17, 18, 30, 31, 32, 47, 48]:
        msg = det(f"mmo-{n}", n)
        lines.append(f"  {{{c_bytes(msg)}, {n}, {c_bytes(mmo(msg))}}},")
    lines.append("};")
    lines.append("typedef struct { uint8_t key[16]; uint8_t msg[33]; size_t len; uint8_t mac[16]; } hmac_vec_t;")
    lines.append("static const hmac_vec_t HMAC_VECTORS[] = {")
    for n in [1, 16, 33]:
        k, msg = det(f"hmac-k{n}", 16), det(f"hmac-m{n}", n)
        lines.append(f"  {{{c_bytes(k)}, {c_bytes(msg)}, {n}, {c_bytes(hmac_mmo(k, msg))}}},")
    lines.append("};")
    # Secured NWK data frame: header, aux (on-air level 0), ENC-MIC-32.
    nwk_key = det("nwk-key", 16)
    src_ieee = det("nwk-src", 8)
    counter = 0x00012345
    header = bytes([0x08, 0x12, 0x00, 0x00, 0x34, 0x12, 0x1E, 0x42]) + src_ieee  # data, v2, sec, src IEEE
    aux_onair = bytes([0x28]) + counter.to_bytes(4, "little") + src_ieee + bytes([0x00])
    aux_aad = bytes([0x2D]) + aux_onair[1:]
    payload = det("nwk-payload", 21)
    nonce = src_ieee + counter.to_bytes(4, "little") + bytes([0x2D])
    sealed = AESCCM(nwk_key, tag_length=4).encrypt(nonce, payload, header + aux_aad)
    frame = header + aux_onair + sealed
    lines.append(f"static const uint8_t NWK_KEY[16] = {c_bytes(nwk_key)};")
    lines.append(f"static const uint8_t NWK_SRC_IEEE[8] = {c_bytes(src_ieee)};")
    lines.append(f"static const uint8_t NWK_PLAINTEXT[{len(payload)}] = {c_bytes(payload)};")
    lines.append(f"static const uint8_t NWK_SECURED_FRAME[{len(frame)}] = {c_bytes(frame)};")
    lines.append(f"#define NWK_SECURED_HEADER_LEN {len(header)}u")
    lines.append(f"#define NWK_SECURED_COUNTER 0x{counter:08x}u")
    # APS Transport Key (standard network key) from the Trust Center to a
    # joining device, secured with the key-transport key = HMAC-MMO(TCLK, 0x00),
    # APS aux header: key id 2, extended nonce, on-air level 0 (real level 5).
    tclk = b"ZigBeeAlliance09"
    ktk = hmac_mmo(tclk, bytes([0]))
    tc_ieee = bytes.fromhex("0403020100 4b1200".replace(" ", ""))   # 0x00124B0001020304 LE
    dev_ieee = bytes.fromhex("0100000000 38c1a4".replace(" ", ""))  # 0xA4C1380000000001 LE
    aps_counter, aps_fc = 0x37, 0x00000102
    aps_hdr = bytes([0x21, aps_counter])                       # command, unicast, security
    aux_air = bytes([0x30]) + aps_fc.to_bytes(4, "little") + tc_ieee
    aux_aad = bytes([0x35]) + aux_air[1:]
    tk_payload = bytes([0x05, 0x01]) + nwk_key + bytes([0x00]) + dev_ieee + tc_ieee
    tk_nonce = tc_ieee + aps_fc.to_bytes(4, "little") + bytes([0x35])
    tk_sealed = AESCCM(ktk, tag_length=4).encrypt(tk_nonce, tk_payload, aps_hdr + aux_aad)
    nwk_hdr = bytes([0x08, 0x00, 0x21, 0x4E, 0x00, 0x00, 0x1E, 0x10])   # data v2, dst 0x4E21, src 0, r30, seq 16
    lines.append(f"static const uint8_t TK_KEY_TRANSPORT_KEY[16] = {c_bytes(ktk)};")
    lines.append(f"static const uint8_t TK_FRAME[{len(nwk_hdr + aps_hdr + aux_air + tk_sealed)}] = "
                 f"{c_bytes(nwk_hdr + aps_hdr + aux_air + tk_sealed)};")
    lines.append(f"#define TK_APS_COUNTER 0x{aps_counter:02x}u")
    lines.append(f"#define TK_APS_FRAME_COUNTER 0x{aps_fc:08x}u")
    lines.append("#endif")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
